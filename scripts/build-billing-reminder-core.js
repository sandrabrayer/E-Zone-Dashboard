'use strict';

// Reproducible Apps Script bundle: identical queue rules and a date table from
// the tested calendar. No runtime Intl/require or new production dependency.
const fs = require('node:fs');
const path = require('node:path');
const calendar = require('../lib/billing-work-calendar');
const ROOT = path.join(__dirname, '..');
function tableCalendar(table) {
  const DAY = 86400000;
  function parse(iso) {
    if (typeof iso !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return null;
    const d = new Date(iso + 'T00:00:00Z'), y = Number(iso.slice(0, 4));
    if (!table[y] || !Number.isFinite(d.getTime()) || d.toISOString().slice(0, 10) !== iso) return null;
    return { y, n: d.getTime() / DAY, i: (d.getTime() - Date.UTC(y, 0, 1)) / DAY };
  }
  function isBusinessDay(iso, owner) {
    const d = parse(iso);
    return !d || !['vered', 'ortal'].includes(owner) ? null : table[d.y][owner][d.i] === '1';
  }
  function businessDaysBetween(opened, asOf, owner) {
    const a = parse(opened), b = parse(asOf);
    if (!a || !b || !['vered', 'ortal'].includes(owner)) return null;
    if (a.n >= b.n) return 0;
    let count = 0;
    for (let y = a.y; y <= b.y; y++) {
      const from = y === a.y ? a.i + 1 : 0, to = y === b.y ? b.i + 1 : table[y][owner].length;
      for (const bit of table[y][owner].slice(from, to)) if (bit === '1') count++;
    }
    return count;
  }
  return { isBusinessDay, businessDaysBetween };
}
function build() {
  const table = {};
  for (let y = 2020; y <= 2035; y++) {
    table[y] = { vered: '', ortal: '' };
    for (let n = Date.UTC(y, 0, 1); n < Date.UTC(y + 1, 0, 1); n += 86400000) {
      const day = new Date(n).toISOString().slice(0, 10);
      for (const owner of ['vered', 'ortal']) {
        const work = calendar.isBusinessDay(day, owner);
        if (work === null) throw new Error('Cannot build calendar');
        table[y][owner] += work ? '1' : '0';
      }
    }
  }
  const rules = fs.readFileSync(path.join(ROOT, 'lib/billing-control-rules.js'), 'utf8');
  const mail = fs.readFileSync(path.join(ROOT, 'lib/billing-reminder-mail.js'), 'utf8');
  return '// GENERATED by node scripts/build-billing-reminder-core.js; do not edit.\n' +
    'var BillingReminderCore = (function () {\nconst calendar = (' + tableCalendar.toString() + ')(' + JSON.stringify(table) + ');\n' +
    'const rules = (function (module, require) {\n' + rules + '\nreturn module.exports;\n})({exports:{}}, function (id) { if (id === "./billing-work-calendar") return calendar; throw new Error("Unknown module"); });\n' +
    'return (function (module, require) {\n' + mail + '\nreturn module.exports;\n})({exports:{}}, function (id) { if (id === "./billing-work-calendar") return calendar; if (id === "./billing-control-rules") return rules; throw new Error("Unknown module"); });\n})();\n';
}
if (require.main === module) fs.writeFileSync(path.join(ROOT, 'apps-script/BillingReminderCore.gs'), build());
module.exports = { build };
